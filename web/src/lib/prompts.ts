/** タグ集合から決定論的に 0..n-1 の index を作る。 */
function steerIndex(tags: string[], n: number): number {
  const s = tags.join("|");
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return h % n;
}

